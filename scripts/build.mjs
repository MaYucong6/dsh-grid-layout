/**
 * 构建 lib/ 产物（对齐 dsh-boot-animation 的真实产物布局）。
 *
 *   lib/index.js            Host 入口转发：export { apply, name, inject }
 *   lib/host/index.js       Host 实现（Node ESM，node: 内置模块 external）
 *   lib/client.js           Client 端，包装成 DSH 的 __ModuleLoader__.load({...}) 格式
 *   lib/types/*.d.ts        类型声明
 *
 * 用法：npm run build
 */
import { build } from 'esbuild'
import { mkdirSync, writeFileSync, rmSync } from 'node:fs'
import { dirname } from 'node:path'

const out = (p) => {
  mkdirSync(dirname(p), { recursive: true })
  return p
}

rmSync('lib', { recursive: true, force: true })

// ─────────────────────────────────────────────────────────────
// 1. Host 端（Node ESM；node: 内置模块保持 external）
// ─────────────────────────────────────────────────────────────
await build({
  entryPoints: ['src/host/index.ts'],
  outfile: 'lib/host/index.js',
  bundle: true,
  format: 'esm',
  platform: 'node',
  target: 'node20',
  packages: 'external',
  logLevel: 'info',
})

// 2. Host 入口转发（main / exports["."] 指向这里）
writeFileSync(
  out('lib/index.js'),
  '/**\n' +
    ' * Generated by scripts/build.mjs. Do not edit — edit src/host/index.ts.\n' +
    ' *\n' +
    ' * Host 实现放在 ./host/，本文件存在是因为 main 与 exports 都指向 lib/index.js。\n' +
    ' */\n' +
    "export { apply, name, inject } from './host/index.js'\n",
)

// ─────────────────────────────────────────────────────────────
// 3. Client 端：先打成 CJS 单文件，再包进 DSH 的 module loader 外壳
//    react 由 loader 的 require 提供，因此必须 external。
// ─────────────────────────────────────────────────────────────
const client = await build({
  entryPoints: ['src/client/index.ts'],
  bundle: true,
  format: 'cjs',
  platform: 'browser',
  target: 'es2022',
  external: ['react'],
  write: false,
  logLevel: 'info',
})
const code = client.outputFiles[0].text
const indent = (s) => s.split('\n').map((l) => (l ? '\t\t' + l : l)).join('\n')

writeFileSync(
  out('lib/client.js'),
  'window.__ModuleLoader__.load({\n' +
    '\tid: "dsh-grid-layout",\n' +
    '\tfactory: (require) => {\n' +
    '\t\tvar module = { exports: {} };\n' +
    '\t\tvar exports = module.exports;\n' +
    '\t\tObject.defineProperty(exports, Symbol.toStringTag, { value: "Module" });\n' +
    indent(code) +
    '\n\t\treturn module.exports;\n' +
    '\t}\n' +
    '});\n',
)

// ─────────────────────────────────────────────────────────────
// 4. 类型声明
// ─────────────────────────────────────────────────────────────
writeFileSync(
  out('lib/types/index.d.ts'),
  '/** Host half of dsh-grid-layout. */\n' +
    'export declare const name: string\n' +
    'export declare const inject: string[]\n' +
    'export declare function apply(ctx: unknown): void\n',
)
writeFileSync(
  out('lib/types/client/index.d.ts'),
  '/** Browser half of dsh-grid-layout. */\n' +
    'export declare const inject: string[]\n' +
    'export declare function apply(ctx: unknown): void\n',
)

console.log('[dsh-grid-layout] built lib/ (host + client + types)')
